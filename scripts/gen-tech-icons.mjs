/**
 * Generates data/techIcons.ts from the `simple-icons` package (a devDependency).
 * We embed only the ~15 brand SVG paths we actually render, so `simple-icons`
 * never ships to the client bundle. simple-icons artwork is CC0.
 *
 * Run:  node scripts/gen-tech-icons.mjs
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// name shown in the UI  ->  simple-icons slug
const WANT = {
  // Streaming & Processing
  "Apache Kafka": "apachekafka",
  "Apache Spark": "apachespark",
  "Apache Airflow": "apacheairflow",
  dbt: "dbt",
  Databricks: "databricks",
  // Cloud & Storage  (Azure has no simple-icons mark — Microsoft brands were
  // removed upstream, so it falls back to a lucide icon in CoreTech.tsx)
  AWS: "amazonwebservices",
  Snowflake: "snowflake",
  PostgreSQL: "postgresql",
  Redis: "redis",
  MongoDB: "mongodb",
  // MLOps & AI  (Pinecone has no simple-icons mark → lucide fallback)
  Docker: "docker",
  Kubernetes: "kubernetes",
  Terraform: "terraform",
  MLflow: "mlflow",
  LangChain: "langchain",
};

const out = {};
for (const [name, slug] of Object.entries(WANT)) {
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) {
    console.warn(`[tech-icons] missing: ${name} (${slug}) — will fall back to a lucide icon`);
    continue;
  }
  out[name] = icon.path;
}

const file = `// AUTO-GENERATED by scripts/gen-tech-icons.mjs — do not edit by hand.
// Brand SVG paths from simple-icons (https://simpleicons.org), licensed CC0.
// Rendered monochrome (currentColor) in components/CoreTech.tsx.

export const techIconPaths: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(join(root, "data", "techIcons.ts"), file);
console.log(`[tech-icons] wrote data/techIcons.ts with ${Object.keys(out).length} icons`);
