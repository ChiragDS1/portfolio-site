/**
 * Generates data/techIcons.ts from the `simple-icons` package (a devDependency).
 * We embed only the ~15 brand SVG paths we actually render, so `simple-icons`
 * never ships to the client bundle. simple-icons artwork is CC0.
 *
 * Run:  node scripts/gen-tech-icons.mjs
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// name shown in the UI  ->  simple-icons slug
const WANT = {
  // Streaming & Processing
  Kafka: "apachekafka",
  Spark: "apachespark",
  Airflow: "apacheairflow",
  dbt: "dbt",
  Databricks: "databricks",
  Python: "python",
  // Cloud & Warehouses  (Azure / Data Factory / Synapse are Microsoft marks,
  // removed from simple-icons upstream — rendered as text badges instead)
  AWS: "amazonwebservices",
  Snowflake: "snowflake",
  PostgreSQL: "postgresql",
  // Platforms, MLOps & AI  (no upstream mark for Pinecone)
  Docker: "docker",
  Kubernetes: "kubernetes",
  Terraform: "terraform",
  MLflow: "mlflow",
  LangChain: "langchain",
  Redis: "redis",
};

/** WCAG relative luminance, used to decide if a brand color survives a tile. */
function luminance(h) {
  const ch = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const [r, g, b] = ch.map((c) => (c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const out = {};
for (const [name, slug] of Object.entries(WANT)) {
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) {
    console.warn(`[tech-icons] missing: ${name} (${slug}) — will fall back to a lucide icon`);
    continue;
  }
  out[name] = { path: icon.path, hex: `#${icon.hex}`, lum: +luminance(icon.hex).toFixed(4) };
}

const file = `// AUTO-GENERATED by scripts/gen-tech-icons.mjs — do not edit by hand.
// Brand SVG paths + brand colors from simple-icons (https://simpleicons.org), CC0.
// Rendered in brand color in components/worlds/ToolkitGrid.tsx; tools whose brand
// color is too dark to read on a dark tile fall back to the text color there.

export interface TechIcon {
  path: string;
  /** Official brand color. */
  hex: string;
  /** WCAG relative luminance of \`hex\`, so a tile can reject it when it would
   *  disappear against its own background (see ToolkitGrid). */
  lum: number;
}

export const techIcons: Record<string, TechIcon> = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(join(root, "data", "techIcons.ts"), file);
console.log(`[tech-icons] wrote data/techIcons.ts with ${Object.keys(out).length} icons`);
